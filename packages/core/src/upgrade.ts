import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import type { Deps } from "./deps.ts";

/** What a ref may look like: a branch, tag or commit. Never an option for git or the installer. */
export const REF_RE = /^[A-Za-z0-9][A-Za-z0-9._/-]{0,99}$/;
export const validRef = (ref: string) => REF_RE.test(ref) && !ref.includes("..");

export const UPGRADE_STATES = ["running", "verifying", "rolling-back", "done", "rolled-back", "failed"] as const;
export type UpgradeState = (typeof UPGRADE_STATES)[number];
const ACTIVE: readonly UpgradeState[] = ["running", "verifying", "rolling-back"];
const UNIT = "freighter-upgrade";

export interface UpgradeInfo {
  state: UpgradeState;
  from: string | null;
  to: string | null;
  ref: string | null;
  startedAt: string | null;
  updatedAt: string | null;
  message: string | null;
}

export interface UpgradeStatus {
  /** Whether this agent can upgrade itself (it must be an installer-made git checkout, on a real server). */
  supported: boolean;
  reason: string | null;
  /** The commit it runs now. */
  commit: string | null;
  upgrade: UpgradeInfo | null;
  /** Tail of the upgrade log. */
  log: string;
  /** Whose HAProxy this server uses. */
  haproxy: { mode: HaproxyMode };
}

export type HaproxyMode = "dedicated" | "existing";

/**
 * Whether the installer set up its own HAProxy for Freighter (`dedicated`: Freighter owns the config) or wired into one
 * that was already there (`existing`: the operator owns it). The installer records its choice in `<haproxy.dir>/mode`;
 * servers installed before that guess from where the config lives.
 */
export async function haproxyMode(d: Deps): Promise<HaproxyMode> {
  const recorded = await read(`${d.config.haproxy.dir}/mode`);
  if (recorded === "dedicated" || recorded === "existing") return recorded;
  return d.config.haproxy.mainConfig.startsWith("/etc/freighter/haproxy/") ? "dedicated" : "existing";
}

export class UpgradeError extends Error {}

const read = async (path: string) => (await readFile(path, "utf8").catch(() => "")).trim() || null;

const q = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

export interface UpgradeScriptOptions {
  stateDir: string;
  installDir: string;
  ref: string;
  /** `dedicated` (Freighter's own HAProxy) or `existing`; passed to the installer so it doesn't guess. */
  haproxy: "dedicated" | "existing";
  /** The HAProxy config Freighter manages in the dedicated setup: restored on rollback. */
  haproxyMain: string;
  haproxyReload: string[];
  confirmSeconds: number;
  /** Stay on the installed version (ignore `ref`) and add Podman: the installer runs with `--with-containers`. */
  withContainers?: boolean;
}

/**
 * The script the upgrade runs as (a transient systemd unit, so it outlives the agent restarting in the middle of it).
 *
 *   1. back up what an upgrade replaces: the built agent and CLI, the units, a Freighter-managed haproxy.cfg
 *   2. fetch the ref and run *its* installer, the same code as a fresh install
 *   3. wait for the control plane to confirm it can reach the new agent over mTLS (`upgrade.confirm`)
 *   4. no confirmation within the time, or the installer fails: put the backup back and restart the old agent
 *
 * The agent is bundled to single files, so restoring dist/ is enough; nothing is rebuilt on the way back.
 */
export function renderUpgradeScript(o: UpgradeScriptOptions): string {
  return `#!/bin/sh
# Generated by freighter-agent for one upgrade. Output goes to $STATE/log.
STATE=${q(o.stateDir)}
DIR=${q(o.installDir)}
REF=${q(o.ref)}
MODE=${q(o.haproxy)}
MAIN=${q(o.haproxyMain)}
RELOAD=${q(o.haproxyReload.map(q).join(" "))}
CONFIRM_SECONDS=${Math.max(1, Math.floor(o.confirmSeconds))}
WITH_CONTAINERS=${o.withContainers ? 1 : 0}
UNIT_DIR=\${FREIGHTER_UNIT_DIR:-/etc/systemd/system}
POLL=\${FREIGHTER_POLL_SECONDS:-2}

mkdir -p "$STATE"
exec >>"$STATE/log" 2>&1

now() { date -u +%Y-%m-%dT%H:%M:%SZ; }
say() { printf '[%s] %s\\n' "$(now)" "$*"; }
set_state() { printf '%s\\n' "$1" >"$STATE/state"; now >"$STATE/updated"; if [ $# -gt 1 ]; then printf '%s\\n' "$2" >"$STATE/message"; fi; say "$1: \${2:-}"; }

rollback() {
  set_state rolling-back "$1"
  ok=1
  git -C "$DIR" checkout --quiet --force "$FROM" || ok=0
  rm -rf "$DIR/apps/agent/dist" "$DIR/apps/cli/dist"
  cp -a "$STATE/backup/agent-dist" "$DIR/apps/agent/dist" || ok=0
  cp -a "$STATE/backup/cli-dist" "$DIR/apps/cli/dist" || ok=0
  for f in "$STATE"/backup/units/*; do [ -e "$f" ] && cp -a "$f" "$UNIT_DIR/"; done
  systemctl daemon-reload || true
  if [ -f "$STATE/backup/haproxy.cfg" ]; then
    cp -a "$STATE/backup/haproxy.cfg" "$MAIN" && { eval "$RELOAD" || say "could not reload HAProxy"; }
  fi
  systemctl restart freighter-agent || ok=0
  if [ "$ok" = 1 ]; then
    set_state rolled-back "$1. Restored $(printf '%s' "$FROM" | cut -c1-12), the version that was running."
  else
    set_state failed "$1. Putting the old version back failed too: this server needs a manual look (see $STATE/log)."
  fi
}

rm -f "$STATE/confirmed" "$STATE/to" "$STATE/message"
now >"$STATE/started"
printf '%s\\n' "$REF" >"$STATE/ref"
set_state running "Backing up the current version"
FROM=$(git -C "$DIR" rev-parse HEAD) || { set_state failed "$DIR is not a git checkout"; exit 1; }
printf '%s\\n' "$FROM" >"$STATE/from"
# Adding container support does not change the version: re-run the installer for the commit that is installed.
if [ "$WITH_CONTAINERS" = 1 ]; then REF=$FROM; printf '%s\\n' "$REF" >"$STATE/ref"; fi
rm -rf "$STATE/backup"; mkdir -p "$STATE/backup/units"
cp -a "$DIR/apps/agent/dist" "$STATE/backup/agent-dist" && cp -a "$DIR/apps/cli/dist" "$STATE/backup/cli-dist" \\
  || { set_state failed "Could not back up the current version, so nothing was changed"; exit 1; }
for f in "$UNIT_DIR"/freighter-*; do [ -e "$f" ] && cp -a "$f" "$STATE/backup/units/"; done
if head -n1 "$MAIN" 2>/dev/null | grep -q '^# Managed by freighter'; then cp -a "$MAIN" "$STATE/backup/haproxy.cfg"; fi

set_state running "Fetching $REF"
if ! out=$(git -C "$DIR" fetch --quiet --depth 1 origin "$REF" 2>&1); then
  # git can't fetch a commit by an abbreviation. Look for it in the recent history of the branches and use the full one.
  full=
  case $REF in
    *[!0-9a-f]*|'') ;;
    *) if [ "\${#REF}" -ge 7 ] && [ "\${#REF}" -lt 40 ]; then
         say "$REF looks like an abbreviated commit; looking for it in the branches' history"
         git -C "$DIR" fetch --quiet --depth 200 origin '+refs/heads/*:refs/freighter-resolve/*' >/dev/null 2>&1 \
           && full=$(git -C "$DIR" rev-parse --verify --quiet "$REF^{commit}") || full=
       fi ;;
  esac
  git -C "$DIR" for-each-ref --format='delete %(refname)' refs/freighter-resolve/ | git -C "$DIR" update-ref --stdin >/dev/null 2>&1 || true
  if [ -n "$full" ] && out=$(git -C "$DIR" fetch --quiet --depth 1 origin "$full" 2>&1); then
    say "$REF is $full"
    REF=$full
    printf '%s\n' "$REF" >"$STATE/ref"
  else
    set_state failed "Could not fetch $REF from the repository, so nothing was changed. git said: $(printf '%s' "$out" | tail -n 1)"
    exit 1
  fi
fi
TO=$(git -C "$DIR" rev-parse FETCH_HEAD) && printf '%s\\n' "$TO" >"$STATE/to"
git -C "$DIR" show FETCH_HEAD:infra/install.sh >"$STATE/install.sh" || { set_state failed "$REF has no infra/install.sh, so nothing was changed"; exit 1; }

if [ "$WITH_CONTAINERS" = 1 ]; then
  set_state running "Adding container support: installing Podman and re-running the installer for $(printf '%s' "$TO" | cut -c1-12) (a few minutes)"
  set -- --with-containers
else
  set_state running "Installing $(printf '%s' "$TO" | cut -c1-12) (this builds Freighter on the server and takes a few minutes)"
  set --
fi
if ! sh "$STATE/install.sh" --role agent --ref "$REF" --dir "$DIR" --haproxy "$MODE" "$@"; then
  rollback "The installer failed"
  exit 1
fi

set_state verifying "Installed. Waiting for the control plane to confirm it can reach the new agent"
i=0
while [ ! -e "$STATE/confirmed" ] && [ "$i" -lt "$CONFIRM_SECONDS" ]; do
  sleep "$POLL"
  i=$((i + POLL))
done
if [ -e "$STATE/confirmed" ]; then
  if [ "$WITH_CONTAINERS" = 1 ]; then set_state done "Container support added: Podman is installed and the agent restarted"
  else set_state done "Upgraded from $(printf '%s' "$FROM" | cut -c1-12) to $(printf '%s' "$TO" | cut -c1-12)"; fi
  exit 0
fi
rollback "The control plane did not confirm the new agent within \${CONFIRM_SECONDS}s"
exit 1
`;
}

const dirOf = (d: Deps) => d.config.agent.upgradeDir;

async function unitActive(d: Deps): Promise<boolean> {
  return (await d.run("systemctl", ["is-active", "--quiet", UNIT])).code === 0;
}

function unsupported(d: Deps): string | null {
  if (d.dev) return "Upgrades only run on real servers.";
  if (!d.isRoot) return "The agent must run as root to upgrade itself.";
  if (!d.installDir) return "This agent was not installed by the installer (no git checkout), so it can't upgrade itself.";
  return null;
}

/** What the last upgrade did. One that claims to run while its unit is gone (a reboot, a crash) is reported as failed. */
export async function upgradeStatus(d: Deps, commit: string | null): Promise<UpgradeStatus> {
  const dir = dirOf(d);
  const state = (await read(`${dir}/state`)) as UpgradeState | null;
  let upgrade: UpgradeInfo | null = null;
  if (state && UPGRADE_STATES.includes(state)) {
    upgrade = {
      state,
      from: await read(`${dir}/from`),
      to: await read(`${dir}/to`),
      ref: await read(`${dir}/ref`),
      startedAt: await read(`${dir}/started`),
      updatedAt: await read(`${dir}/updated`),
      message: await read(`${dir}/message`),
    };
    if (ACTIVE.includes(state) && !(await unitActive(d))) {
      upgrade = { ...upgrade, state: "failed", message: "The upgrade was interrupted before it finished (the server may have restarted)." };
    }
  }
  const log = (await readFile(`${dir}/log`, "utf8").catch(() => "")).split("\n").slice(-80).join("\n").slice(-16_000);
  const reason = unsupported(d);
  return { supported: reason === null, reason, commit, upgrade, log, haproxy: { mode: await haproxyMode(d) } };
}

/** Start upgrading to `ref`. Returns as soon as the upgrade is running on its own. */
export async function startUpgrade(d: Deps, ref: string, commit: string | null, opts: { withContainers?: boolean } = {}): Promise<void> {
  const reason = unsupported(d);
  if (reason) throw new UpgradeError(reason);
  if (!validRef(ref)) throw new UpgradeError(`invalid ref "${ref}"`);
  const status = await upgradeStatus(d, commit);
  if (status.upgrade && ACTIVE.includes(status.upgrade.state)) throw new UpgradeError("an upgrade is already in progress");

  const dir = dirOf(d);
  await mkdir(dir, { recursive: true });
  const script = `${dir}/upgrade.sh`;
  const mode = await haproxyMode(d);
  await writeFile(
    script,
    renderUpgradeScript({
      stateDir: dir,
      installDir: d.installDir!,
      ref,
      haproxy: mode,
      haproxyMain: d.config.haproxy.mainConfig,
      haproxyReload: d.config.haproxy.reloadCommand,
      confirmSeconds: 180,
      withContainers: opts.withContainers,
    }),
    { mode: 0o700 },
  );
  // A new run starts from nothing: the previous run's log and result must not show through.
  await Promise.all(["from", "to", "started", "updated", "confirmed"].map((f) => rm(`${dir}/${f}`, { force: true })));
  await writeFile(`${dir}/log`, "");
  await writeFile(`${dir}/state`, "running\n");
  await writeFile(`${dir}/message`, "Starting\n");
  await writeFile(`${dir}/ref`, `${ref}\n`);
  const r = await d.run("systemd-run", [`--unit=${UNIT}`, "--description=Freighter agent upgrade", "--collect", "/bin/sh", script]);
  if (r.code !== 0) {
    await writeFile(`${dir}/state`, "failed\n");
    const why = (r.stderr ?? r.stdout).trim().split("\n").slice(-2).join(" | ");
    await writeFile(`${dir}/message`, `Could not start the upgrade: ${why}\n`);
    throw new UpgradeError(`could not start the upgrade (systemd-run exit ${r.code}): ${why}`);
  }
}

export interface RepoCommit {
  commit: string;
  subject: string;
  committedAt: string;
}
export interface UpdateCheck {
  /** The branch, tag or commit that was asked about. */
  ref: string;
  installed: RepoCommit | null;
  /** What `ref` points at on the repository right now. */
  latest: RepoCommit;
  /**
   * `up-to-date`: installed is `latest`. `behind`: `latest` has newer commits. `ahead`: installed is newer than `ref`.
   * `different`: the two aren't in a line (another branch, a rewritten history, or more than 50 commits apart).
   */
  state: "up-to-date" | "behind" | "ahead" | "different";
  /** How many commits `latest` is ahead, when that is known. */
  behind: number | null;
  /** The newest of those commits, newest first (at most 20). */
  commits: { sha: string; subject: string }[];
  checkedAt: string;
}

const FIELDS = "%H%x09%cI%x09%s";
const parseCommit = (line: string): RepoCommit | null => {
  const [commit, committedAt, ...subject] = line.trim().split("\t");
  return commit && committedAt ? { commit, committedAt, subject: subject.join("\t") } : null;
};

/**
 * Ask the repository this server was installed from what's new, using the server's own git (so its network, its
 * credentials and its `origin` decide the answer, not the control plane's). Fetches the last 50 commits of `ref` into
 * the checkout's object store and compares; nothing in the working tree changes.
 */
export async function checkForUpdates(d: Deps, ref: string): Promise<UpdateCheck> {
  const reason = unsupported(d);
  if (reason) throw new UpgradeError(reason);
  if (!validRef(ref)) throw new UpgradeError(`invalid ref "${ref}"`);
  const status = await upgradeStatus(d, null);
  if (status.upgrade && ACTIVE.includes(status.upgrade.state)) throw new UpgradeError("an upgrade is in progress");

  const dir = d.installDir!;
  const git = (args: string[], timeoutMs = 20_000) => d.exec("git", ["-C", dir, ...args], { timeoutMs, env: { GIT_TERMINAL_PROMPT: "0" } });
  const fetched = await git(["fetch", "--quiet", "--depth", "50", "origin", ref], 90_000).catch((e: unknown) => ({ code: 1, stdout: "", stderr: e instanceof Error ? e.message : String(e) }));
  if (fetched.code !== 0) {
    const why = (fetched.stderr ?? "").trim().split("\n").slice(-2).join(" | ");
    throw new UpgradeError(`could not fetch ${ref} from origin: ${why || `git exited ${fetched.code}`}`);
  }
  const latest = parseCommit((await git(["log", "-1", `--format=${FIELDS}`, "FETCH_HEAD"])).stdout);
  if (!latest) throw new UpgradeError(`origin has no ${ref}`);
  const installed = parseCommit((await git(["log", "-1", `--format=${FIELDS}`, "HEAD"])).stdout);

  let state: UpdateCheck["state"] = "different";
  let behind: number | null = null;
  let commits: UpdateCheck["commits"] = [];
  if (installed?.commit === latest.commit) {
    state = "up-to-date";
    behind = 0;
  } else if ((await git(["merge-base", "--is-ancestor", "HEAD", "FETCH_HEAD"])).code === 0) {
    state = "behind";
    behind = Number((await git(["rev-list", "--count", "HEAD..FETCH_HEAD"])).stdout.trim()) || null;
    commits = (await git(["log", "-n", "20", "--format=%h%x09%s", "HEAD..FETCH_HEAD"])).stdout
      .split("\n")
      .filter(Boolean)
      .map((l) => ({ sha: l.split("\t")[0]!, subject: l.split("\t").slice(1).join("\t") }));
  } else if ((await git(["merge-base", "--is-ancestor", "FETCH_HEAD", "HEAD"])).code === 0) {
    state = "ahead";
  }
  return { ref, installed, latest, state, behind, commits, checkedAt: d.now().toISOString() };
}

/** The control plane saw the new agent answer: let the waiting upgrade finish instead of rolling back. */
export async function confirmUpgrade(d: Deps): Promise<boolean> {
  const dir = dirOf(d);
  if ((await read(`${dir}/state`)) !== "verifying" || !(await unitActive(d))) return false;
  await writeFile(`${dir}/confirmed`, "ok\n");
  return true;
}
